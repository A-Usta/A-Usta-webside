CREATE OR REPLACE FUNCTION austa_private.v36_track_price()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $fn$
DECLARE s text; old_price numeric; new_price numeric; old_currency text; new_currency text; event_time timestamptz;
BEGIN
 s:=CASE TG_TABLE_NAME WHEN 'vehicle_listings' THEN 'vehicle' ELSE 'marketplace' END;
 IF s='vehicle' THEN old_price:=COALESCE(OLD.daily_price,OLD.price); new_price:=COALESCE(NEW.daily_price,NEW.price);old_currency:='AZN';new_currency:='AZN';
 ELSE old_price:=OLD.price; new_price:=NEW.price;old_currency:=OLD.currency;new_currency:=NEW.currency; END IF;
 IF NEW.status<>'active' OR new_price IS NULL OR new_price<0 THEN RETURN NEW; END IF;
 event_time:=COALESCE(NEW.updated_at,clock_timestamp());
 IF TG_OP='INSERT' THEN
  INSERT INTO austa_private.listing_price_history(listing_source,listing_id,price,currency,changed_at,initial_known) VALUES(s,NEW.id,new_price,new_currency,event_time,true) ON CONFLICT DO NOTHING;
 ELSIF OLD.status<>'active' THEN
  INSERT INTO austa_private.listing_price_history(listing_source,listing_id,price,currency,changed_at,initial_known) VALUES(s,NEW.id,new_price,new_currency,event_time,true) ON CONFLICT DO NOTHING;
 ELSIF old_price IS DISTINCT FROM new_price OR old_currency IS DISTINCT FROM new_currency THEN
  INSERT INTO austa_private.listing_price_history(listing_source,listing_id,price,currency,changed_at,initial_known) VALUES(s,NEW.id,new_price,new_currency,event_time,false) ON CONFLICT DO NOTHING;
 END IF;
 RETURN NEW;
END;
$fn$;
REVOKE ALL ON FUNCTION austa_private.v36_track_price() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS austa_v36_price_history ON public.vehicle_listings;
CREATE TRIGGER austa_v36_price_history AFTER INSERT OR UPDATE OF status,price,daily_price ON public.vehicle_listings FOR EACH ROW EXECUTE FUNCTION austa_private.v36_track_price();
DROP TRIGGER IF EXISTS austa_v36_price_history ON public.marketplace_listings;
CREATE TRIGGER austa_v36_price_history AFTER INSERT OR UPDATE OF status,price,currency ON public.marketplace_listings FOR EACH ROW EXECUTE FUNCTION austa_private.v36_track_price();

CREATE OR REPLACE FUNCTION public.austa_get_listing_detail_metadata(p_source text,p_listing_id uuid)
RETURNS TABLE(public_number bigint,view_count bigint,updated_at timestamptz)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=''
AS $fn$
DECLARE l record;
BEGIN
 IF p_source NOT IN ('vehicle','marketplace','service_provider','auto_dealer') THEN RETURN; END IF;
 SELECT * INTO l FROM austa_private.v36_listing_exists(p_source,p_listing_id,false);
 IF NOT FOUND OR (l.owner_id IS DISTINCT FROM auth.uid() AND NOT EXISTS(SELECT 1 FROM austa_private.v36_listing_exists(p_source,p_listing_id,true))) THEN RETURN; END IF;
 RETURN QUERY SELECT m.public_number,m.view_count,l.updated_at FROM austa_private.listing_detail_metrics m WHERE m.listing_source=p_source AND m.listing_id=p_listing_id;
END;
$fn$;
REVOKE ALL ON FUNCTION public.austa_get_listing_detail_metadata(text,uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.austa_get_listing_detail_metadata(text,uuid) TO anon,authenticated;

CREATE OR REPLACE FUNCTION public.austa_record_listing_detail_view(p_source text,p_listing_id uuid,p_visitor_id uuid)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $fn$
DECLARE l record; count_now bigint; prior timestamptz; visitor uuid;
BEGIN
 IF p_source NOT IN ('vehicle','marketplace','service_provider','auto_dealer') OR p_visitor_id IS NULL THEN RETURN NULL; END IF;
 visitor:=COALESCE(auth.uid(),p_visitor_id);
 PERFORM pg_advisory_xact_lock(hashtext('v36-view:'||visitor::text));
 SELECT * INTO l FROM austa_private.v36_listing_exists(p_source,p_listing_id,true);
 IF NOT FOUND THEN RETURN NULL; END IF;
 SELECT view_count INTO count_now FROM austa_private.listing_detail_metrics WHERE listing_source=p_source AND listing_id=p_listing_id FOR UPDATE;
 IF NOT FOUND THEN RETURN NULL; END IF;
 IF l.owner_id=auth.uid() THEN RETURN count_now; END IF;
 SELECT viewed_at INTO prior FROM austa_private.listing_view_visitors WHERE listing_source=p_source AND listing_id=p_listing_id AND visitor_id=visitor FOR UPDATE;
 IF prior IS NOT NULL AND prior>clock_timestamp()-interval '24 hours' THEN RETURN count_now; END IF;
 IF (SELECT count(*) FROM austa_private.listing_view_visitors WHERE visitor_id=visitor AND viewed_at>clock_timestamp()-interval '24 hours')>=60 THEN RETURN count_now; END IF;
 INSERT INTO austa_private.listing_view_visitors(listing_source,listing_id,visitor_id,viewed_at) VALUES(p_source,p_listing_id,visitor,clock_timestamp())
 ON CONFLICT(listing_source,listing_id,visitor_id) DO UPDATE SET viewed_at=EXCLUDED.viewed_at WHERE austa_private.listing_view_visitors.viewed_at<=clock_timestamp()-interval '24 hours';
 IF NOT FOUND THEN RETURN count_now; END IF;
 UPDATE austa_private.listing_detail_metrics SET view_count=view_count+1 WHERE listing_source=p_source AND listing_id=p_listing_id RETURNING view_count INTO count_now;
 RETURN count_now;
END;
$fn$;
REVOKE ALL ON FUNCTION public.austa_record_listing_detail_view(text,uuid,uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.austa_record_listing_detail_view(text,uuid,uuid) TO anon,authenticated;

CREATE OR REPLACE FUNCTION public.austa_get_listing_price_history(p_source text,p_listing_id uuid)
RETURNS TABLE(price numeric,currency text,changed_at timestamptz,initial_known boolean)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=''
AS $fn$
BEGIN
 IF p_source NOT IN ('vehicle','marketplace') THEN RETURN; END IF;
 IF NOT EXISTS(SELECT 1 FROM austa_private.v36_listing_exists(p_source,p_listing_id,false) l WHERE l.owner_id=auth.uid() OR EXISTS(SELECT 1 FROM austa_private.v36_listing_exists(p_source,p_listing_id,true))) THEN RETURN; END IF;
 RETURN QUERY SELECT h.price,h.currency,h.changed_at,h.initial_known FROM austa_private.listing_price_history h WHERE h.listing_source=p_source AND h.listing_id=p_listing_id ORDER BY h.changed_at,h.id;
END;
$fn$;
REVOKE ALL ON FUNCTION public.austa_get_listing_price_history(text,uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.austa_get_listing_price_history(text,uuid) TO anon,authenticated;

CREATE OR REPLACE FUNCTION public.austa_report_listing(p_source text,p_listing_id uuid,p_reason text,p_details text DEFAULT '')
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $fn$
DECLARE uid uuid:=auth.uid(); report_id uuid; l record; note text:=COALESCE(p_details,'');
BEGIN
 IF uid IS NULL THEN RAISE EXCEPTION 'Authentication required' USING ERRCODE='28000'; END IF;
 IF p_source NOT IN ('vehicle','marketplace','service_provider','auto_dealer') OR p_reason NOT IN ('incorrect_information','misleading_price','inappropriate_content','suspected_fraud','other') OR char_length(note)>2000 THEN RAISE EXCEPTION 'Invalid report'; END IF;
 SELECT * INTO l FROM austa_private.v36_listing_exists(p_source,p_listing_id,true);
 IF NOT FOUND THEN RAISE EXCEPTION 'Listing unavailable'; END IF;
 IF l.owner_id=uid THEN RAISE EXCEPTION 'Cannot report own listing'; END IF;
 INSERT INTO austa_private.listing_reports(reporter_id,listing_source,listing_id,reason,details) VALUES(uid,p_source,p_listing_id,p_reason,note) RETURNING id INTO report_id;
 RETURN report_id;
END;
$fn$;
REVOKE ALL ON FUNCTION public.austa_report_listing(text,uuid,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.austa_report_listing(text,uuid,text,text) TO authenticated;


  listing_source text NOT NULL CHECK (listing_source IN ('vehicle','marketplace','service_provider','auto_dealer')),
  listing_id uuid NOT NULL,
  reason text NOT NULL CHECK (reason IN ('incorrect_information','misleading_price','inappropriate_content','suspected_fraud','other')),

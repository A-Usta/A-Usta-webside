       OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name=t AND column_name='updated_at' AND data_type='timestamp with time zone') THEN
      RAISE EXCEPTION 'V3.6 prerequisite column contract drift: public.%',t;
    END IF;
  END LOOP;
  IF to_regclass('public.vehicle_listings') IS NOT NULL AND NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='vehicle_listings' AND column_name='price') THEN RAISE EXCEPTION 'vehicle price contract missing'; END IF;

CREATE OR REPLACE FUNCTION austa_private.v36_listing_exists(p_source text,p_id uuid,p_active_only boolean DEFAULT true)
RETURNS TABLE(owner_id uuid,updated_at timestamptz,price numeric)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=''
AS $fn$
BEGIN
 IF p_source='vehicle' THEN RETURN QUERY SELECT l.owner_id,l.updated_at,COALESCE(l.daily_price,l.price) FROM public.vehicle_listings l WHERE l.id=p_id AND (NOT p_active_only OR l.status='active');
 ELSIF p_source='marketplace' THEN RETURN QUERY SELECT l.owner_id,l.updated_at,l.price FROM public.marketplace_listings l WHERE l.id=p_id AND (NOT p_active_only OR l.status='active');
 ELSIF p_source='service_provider' THEN RETURN QUERY SELECT l.owner_id,l.updated_at,NULL::numeric FROM public.service_provider_listings l WHERE l.id=p_id AND (NOT p_active_only OR (l.status='active' AND EXISTS(SELECT 1 FROM public.public_service_provider_listings p WHERE p.id=l.id)));
 ELSIF p_source='auto_dealer' THEN RETURN QUERY SELECT l.owner_id,l.updated_at,NULL::numeric FROM public.auto_dealer_listings l WHERE l.id=p_id AND (NOT p_active_only OR l.status='active');
 END IF;
END;
$fn$;
REVOKE ALL ON FUNCTION austa_private.v36_listing_exists(text,uuid,boolean) FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION austa_private.v36_register_listing()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $fn$
DECLARE s text;
BEGIN
 s:=CASE TG_TABLE_NAME WHEN 'vehicle_listings' THEN 'vehicle' WHEN 'marketplace_listings' THEN 'marketplace' WHEN 'service_provider_listings' THEN 'service_provider' ELSE 'auto_dealer' END;
 INSERT INTO austa_private.listing_detail_metrics(listing_source,listing_id) VALUES(s,NEW.id) ON CONFLICT DO NOTHING;
 RETURN NEW;
END;
$fn$;
REVOKE ALL ON FUNCTION austa_private.v36_register_listing() FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION austa_private.v36_touch_listing()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $fn$
BEGIN
 IF (to_jsonb(NEW)-'updated_at') IS DISTINCT FROM (to_jsonb(OLD)-'updated_at') THEN
  NEW.updated_at:=clock_timestamp();
 ELSE
  NEW.updated_at:=OLD.updated_at;
 END IF;
 RETURN NEW;
END;
$fn$;
REVOKE ALL ON FUNCTION austa_private.v36_touch_listing() FROM PUBLIC,anon,authenticated;

